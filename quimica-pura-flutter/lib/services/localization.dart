// Sistema de idiomas de Melli-Qui v4.
// Traduce solo la interfaz (pestañas, botones, onboarding, menú, ajustes).
// El contenido de estudio, las preguntas y los textos de los
// solucionadores siguen en español en esta versión.
//
// El idioma se guarda en el teléfono (SharedPreferences) y la interfaz
// se actualiza en el acto gracias a `notifier` (ValueNotifier).

import 'package:flutter/foundation.dart';

import 'user_prefs.dart';

class AppLang {
  AppLang._();

  /// (código, nombre que se muestra en el selector).
  static const supported = <(String, String)>[
    ('es', 'Español'),
    ('en', 'English'),
    ('fr', 'Français'),
    ('it', 'Italiano'),
    ('pt', 'Português'),
    ('ru', 'Русский'),
  ];

  static String code = 'es';

  /// Cambia de valor cada vez que cambia el idioma: la app entera se
  /// reconstruye escuchando este notifier (ver main.dart).
  static final ValueNotifier<String> notifier = ValueNotifier('es');

  static Future<void> load() async {
    code = UserPrefs.language;
    notifier.value = code;
  }

  static Future<void> setLang(String c) async {
    if (!supported.any((e) => e.$1 == c)) return;
    code = c;
    notifier.value = c;
    await UserPrefs.saveLanguage(c);
  }

  /// Texto de la interfaz en el idioma actual (español si falta la clave).
  static String t(String key) =>
      _strings[code]?[key] ?? _strings['es']![key] ?? key;

  /// Mapa completo de cadenas (para pruebas: comprobar que los 6 idiomas
  /// tienen las mismas claves).
  static Map<String, Map<String, String>> get allStrings => _strings;

  /// Saludo de cada entrada, según el nombre, el género y el idioma.
  static String greeting() {
    if (UserPrefs.userName.isEmpty) return t('greetHi');
    final word =
        UserPrefs.userGender == 'Femenino' ? t('greetF') : t('greetM');
    return '$word ${UserPrefs.userName}';
  }
}

